<?php

namespace App\Mcp\Resources;

use App\Domain\Metrics\MetricFormulas;
use App\Domain\Search\Presets;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\Server\Attributes\Description;
use Laravel\Mcp\Server\Attributes\MimeType;
use Laravel\Mcp\Server\Attributes\Uri;
use Laravel\Mcp\Server\Resource;

/**
 * Ресурс niche-radar://methodology (ТЗ §10): формулы, версии и
 * ограничения источника. Числа агент получает из инструментов, не из
 * этой справки.
 */
#[Uri('niche-radar://methodology')]
#[MimeType('text/markdown')]
#[Description('Методология расчёта метрик, версии формул и ограничения источника данных')]
class MethodologyResource extends Resource
{
    public function handle(Request $request): Response
    {
        $version = MetricFormulas::VERSION;
        $text = <<<MD
        # Методология Niche Radar

        ## Источник данных
        CSV-отчёты популярных запросов Яндекс Wordstat (Bukvarix). Частотность относится к периоду,
        определённому источником; дата сканирования не задаёт длительность периода. Даты замеров
        могут быть неизвестны — тогда ось истории порядковая (замер 1..N от старого к новому),
        календарные и месячные темпы НЕ рассчитываются. «Впервые в рейтинге» (rank_previous = 0)
        не означает «впервые возникший спрос». Отсутствие строки в отчёте, пустая ячейка (NULL)
        и числовой 0 — три разных состояния.

        ## Метрики (версия {$version})
        Для ряда точных частотностей f1..fn от старого к новому, при полном ряде из >= 4 замеров:
        B = (f1 + f2)/2 — ранняя база; R = (f[n-1] + fn)/2 — поздний уровень; A = R − B —
        сглаженный прирост; G = (R − B)/B при B > 0 — сглаженный рост; C = доля переходов
        f[i] > f[i-1] среди n−1 переходов — устойчивость; P = fn / max(f1..fn) — сохранение
        спроса относительно наблюдаемого пика. При неполном ряде эти метрики NULL с причиной
        (insufficient_history / incomplete_series); оценки по выборочным точкам не подставляются.
        Граничное сравнение fn − f1 доступно всегда, когда известны обе границы; процент роста
        не определён при f1 = 0 (причина zero_baseline — «рост от нуля»).

        ## Приоритет исследования (priority_v1)
        При полной истории и B >= 20: priority = round(100 × (0.30·clip(G/2) + 0.25·clip(ln(1+A)/ln(10001))
        + 0.20·C + 0.15·clip(ln(1+fn)/ln(100001)) + 0.10·T)), где T — максимум веса сработавших
        правил признаков задачи (0..1). Приоритет NULL при низкой базе, пропусках или нехватке
        истории. Это рейтинг для первичного отбора, НЕ вероятность успеха и НЕ оценка прибыльности;
        данные о конкуренции в формулу не входят.

        ## Пресеты
        «Устойчивый рост»: >= 4 полных замеров, fn >= 100, B >= 20, A >= 50, G >= 0.30, C >= 0.60, P >= 0.70.
        «Ранние сигналы»: 0 < B < 20, fn >= 50, A >= 30, G >= 1, C >= 0.60, P >= 0.70 — сигнал
        пониженной надёжности. «Рост от нуля»: B = 0, fn >= 50, A >= 30, P >= 0.70 — основная
        метрика роста NULL. «Лидеры роста» / «Лидеры падения» — полный ряд без порогов,
        сортировка по A по убыванию/возрастанию (аналог карточек дашборда): это ранжирование,
        а не отбор по надёжности. Пресеты не смешиваются.

        ## Правила интерпретации
        Широкие частотности не суммируются как объём рынка (они пересекаются). Сумма точных
        частотностей подписывается «суммарная точная частотность выбранных формулировок».
        Изменение ранга не заменяет изменение частотности. Устойчивость в близких замерах —
        описательная характеристика, а не доказательство независимости.

        ## Ограничения v1
        История не склеивается между файлами автоматически; сравнение двух отчётов — только
        текущих замеров при совпадении региона и определения частотности, на пересечении фраз.
        Отсутствующая в следующем отчёте фраза не превращается в ноль.
        MD;

        return Response::text($text);
    }
}
