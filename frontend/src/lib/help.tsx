import { ReactNode } from 'react';
import { HelpSection } from '../components/HelpIcon';

/**
 * Подробные инструкции по работе со страницами (попап по иконке «?»).
 * Тексты раскрывают и смысл метрик, и порядок действий (ТЗ §5).
 */

function P({ children, className }: { children: ReactNode; className?: string }) {
  return <p className={className}>{children}</p>;
}

function UL({ items }: { items: ReactNode[] }) {
  return (
    <ul className="ml-4 list-disc space-y-1">
      {items.map((item, i) => <li key={i}>{item}</li>)}
    </ul>
  );
}

function Kbd({ children }: { children: ReactNode }) {
  return <code className="rounded bg-slate-100 px-1 py-0.5 font-mono text-[11px]">{children}</code>;
}

